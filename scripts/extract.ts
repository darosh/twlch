// Extracts Tailwind's default OKLCH palette into src/data.generated.ts.
// Run: node scripts/extract.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const twDir = require.resolve("tailwindcss/package.json").replace(/package\.json$/, "");
const version: string = JSON.parse(readFileSync(`${twDir}package.json`, "utf8")).version;
const css = readFileSync(`${twDir}theme.css`, "utf8");

const NEUTRAL = new Set([
  "slate",
  "gray",
  "zinc",
  "neutral",
  "stone",
  "mauve",
  "olive",
  "mist",
  "taupe",
]);
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

type Family = { name: string; l: number[]; c: number[]; h: number[] };
const families = new Map<string, Record<number, [number, number, number]>>();

const re = /--color-([a-z]+)-(\d+):\s*oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+|none)\s*\)/g;
for (const m of css.matchAll(re)) {
  const [, name, shade, l, c, h] = m;
  (families.get(name) ?? families.set(name, {}).get(name)!)[Number(shade)] = [
    Math.round(Number(l) * 10) / 1000,
    Number(c),
    h === "none" ? NaN : Number(h),
  ];
}

const chromatic: Family[] = [];
const neutral: Family[] = [];
for (const [name, byShade] of families) {
  for (const s of SHADES) if (!byShade[s]) throw new Error(`${name} missing shade ${s}`);
  // Achromatic colors have hue `none`; borrow the nearest defined hue (0 if the whole family is none).
  const hues = SHADES.map((s) => byShade[s][2]);
  const defined = hues.map((h, i) => (Number.isNaN(h) ? -1 : i)).filter((i) => i >= 0);
  const fillH = hues.map((h, i) =>
    Number.isNaN(h)
      ? defined.length
        ? hues[defined.reduce((a, b) => (Math.abs(b - i) < Math.abs(a - i) ? b : a))]
        : 0
      : h,
  );
  const fam: Family = {
    name,
    l: SHADES.map((s) => byShade[s][0]),
    c: SHADES.map((s) => byShade[s][1]),
    h: fillH,
  };
  (NEUTRAL.has(name) ? neutral : chromatic).push(fam);
}

// Chromatic families sorted by hue at shade 500 so the order follows the hue wheel.
chromatic.sort((a, b) => a.h[5] - b.h[5]);

const hueOf = (fams: Family[]) => fams.map((f) => f.h[5]);
const json = (v: unknown) => JSON.stringify(v);
const header = "// Generated by scripts/extract.ts. Do not edit.\n";
writeFileSync(
  new URL("../src/data.generated.ts", import.meta.url),
  header +
    `import type { Family } from "./data.ts";\n\n` +
    `/** Version of the Tailwind CSS the palette was extracted from. */\n` +
    `export const tailwindVersion = ${json(version)};\n\n` +
    `/** Tailwind's shade labels. */\n` +
    `export const shades: number[] = ${json(SHADES)};\n\n` +
    `/** Chromatic families, sorted by their shade-500 hue. */\n` +
    `export const chromatic: Family[] = ${json(chromatic)};\n\n` +
    `/** Neutral families. */\n` +
    `export const neutral: Family[] = ${json(neutral)};\n\n` +
    `/** Shade-500 hues of the chromatic families, sorted. */\n` +
    `export const chromaticHues: number[] = ${json(hueOf(chromatic))};\n\n` +
    `/** Shade-500 hues of the neutral families. */\n` +
    `export const neutralHues: number[] = ${json(hueOf(neutral))};\n`,
);
console.log(`tailwind ${version}: ${chromatic.length} chromatic, ${neutral.length} neutral`);
